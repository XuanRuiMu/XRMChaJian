package mljy.领域层.任务;

/**
 * 任务状态枚举。
 * 对应需求文档《任务.md》中的任务状态生命周期：
 * 未解锁 → 可接取 → 进行中 → 可交付 → 已完成
 */
public enum 任务状态 {
    /** 未解锁：前置任务尚未完成，看不到任务详情 */
    未解锁,
    /** 可接取：前置任务已完成，可与接取NPC交互接取 */
    可接取,
    /** 进行中：已接取，正在完成目标 */
    进行中,
    /** 可交付：目标已达成，可与交付NPC交互交付 */
    可交付,
    /** 已完成：任务已完成，解锁后续任务 */
    已完成
}
