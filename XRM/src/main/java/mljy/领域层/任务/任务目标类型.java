package mljy.领域层.任务;

/**
 * 任务目标类型枚举。
 * 对应需求文档《任务.md》中的6种任务类型，并扩展技能使用类型。
 */
public enum 任务目标类型 {
    /** 击杀指定实体类型N个（对应"击杀"任务类型） */
    击杀实体,
    /** 收集指定物品N个（对应"收集"任务类型，背包中拥有即可） */
    收集物品,
    /** 到达指定坐标区域（对应"到达位置"任务类型） */
    到达位置,
    /** 与指定NPC对话（对应"对话"任务类型，右键交付NPC即可完成） */
    对话NPC,
    /** 使用指定技能N次（扩展类型，配合技能系统） */
    使用技能,
    /** 条件检查（对应"条件检查"任务类型，如饥饿值达标/使用命令/职业已选择/等级达标等） */
    条件检查,
    /** 护送NPC到达目的地（对应"护送"任务类型，待后续实现） */
    护送
}
