package mljy.领域层.驭空术;

/**
 * 驭空术飞行状态枚举。
 * 状态流转：地面 → 准驭空 → 起飞中 → 飞行中 → 降落中 → 地面。
 */
public enum 飞行状态 {
    /** 地面状态：未激活驭空术。 */
    地面,
    /** 准驭空状态：骑乘状态下第一次按空格后进入，1秒超时。 */
    准驭空,
    /** 起飞中：执行起飞技能，升空过程中。 */
    起飞中,
    /** 飞行中：已进入驭空状态，可使用冲刺/爆发/俯冲技能。 */
    飞行中,
    /** 降落中：正在降落回地面。 */
    降落中
}
