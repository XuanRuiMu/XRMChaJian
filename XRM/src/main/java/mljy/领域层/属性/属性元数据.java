package mljy.领域层.属性;

/**
 * 属性元数据。
 * TD-4 解决方案：将管理命令处理器中硬编码的属性名列表和 switch 映射改为数据驱动。
 *
 * 设计目标（需求.txt第32行"松散性"与"可插入性"）：
 * 1. 松散性——删除任一标准属性注册行，对应命令功能自动消失，不影响其他属性。
 * 2. 可插入性——新增属性（如反伤）只需注册一条 属性元数据，无需修改命令处理器。
 *
 * 字段说明：
 * - 命令名：用户在 /管理 属性 指令中输入的名字（如"生命值""恢复""公CD修正"）。
 * - 修饰器类别：对应修饰器管理器中的类别键，同时也是 属性快照.获取属性值 的查询键。
 * - 显示翻译键：查看属性时使用的翻译键（如"管理员指令.属性.查看.生命值"）。
 */
public record 属性元数据(
        String 命令名,
        String 修饰器类别,
        String 显示翻译键
) {
    public double 取值(属性快照 属性) {
        return 属性.获取属性值(修饰器类别);
    }
}
