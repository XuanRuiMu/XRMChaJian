package mljy.领域层.乐器;

/**
 * FP-04 延音模式。
 * <p>
 * - 按住（默认）：点击音符=开始持续播放，关闭GUI=停止（业界惯例，真实钢琴踏板模式）
 * - 切换（可选）：点击音符=开始延音，再点击同音符=停止（电钢 Sustain 开关模式）
 * <p>
 * 受 MC 原版 playSound「一击即逝」限制，延音通过对同一音以略低音量重复触发若干次模拟自然衰减尾音。
 * half-damper（半踏板）不在本轮实现范围。
 */
public enum 延音模式 {
    按住,
    切换;

    /**
     * 默认延音模式（业界惯例：按住=真实钢琴踏板模式）。
     */
    public static 延音模式 默认模式() {
        return 按住;
    }

    /**
     * 切换到另一种延音模式。
     */
    public 延音模式 切换() {
        return this == 按住 ? 切换 : 按住;
    }
}
