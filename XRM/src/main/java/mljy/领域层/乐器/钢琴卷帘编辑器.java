package mljy.领域层.乐器;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * FP-20 piano roll 简化编辑器（O9）。
 * <p>
 * 受 MC 6×9 GUI 限制的简化版 piano roll 编辑器：
 * <ul>
 *   <li>横向 = 时间（1/16 音符为最小单位，受 MC GUI 槽位限制粒度较粗）</li>
 *   <li>纵向 = 音高（12 音名排列，翻页查看）</li>
 *   <li>编辑操作：删除/移动/复制/改力度/新增（对应需求文档 20.3）</li>
 *   <li>非破坏性：编辑前备份原始乐谱，可恢复（对应需求文档 20.4）</li>
 * </ul>
 * <p>
 * 不可变值对象。每次编辑返回新实例，原始乐谱备份不变。
 * 编辑粒度约束（需求文档 20.4）：
 * <ul>
 *   <li>最小时间单位 = 1/16 音符（按 BPM 100 = 3 tick）</li>
 *   <li>音高范围 = 当前乐器的音域上下限（由调用方校验）</li>
 *   <li>编辑后保存回 NBS 时保留原始作为备份</li>
 * </ul>
 */
public final class 钢琴卷帘编辑器 {
    /**
     * 1/16 音符在 BPM=100 下的 tick 数（1200/100/4=3）。
     * 作为最小编辑粒度，与 量化档位.六十四分音符 的网格点对齐。
     */
    public static final int 最小时间单位tick = 3;

    /**
     * 新增音符的默认时值（1/16 音符 = 3 tick）。
     */
    public static final int 默认新增时值tick = 最小时间单位tick;

    /**
     * piano roll 编辑操作类型（对应需求文档 20.3）。
     */
    public enum 编辑操作 {
        /** 左键点击已有音符 → 删除该音符 */
        删除,
        /** Shift + 左键拖动 → 移动音符到新位置（时间/音高） */
        移动,
        /** Ctrl + 左键拖动 → 复制音符到新位置 */
        复制,
        /** 右键点击音符 → 弹出力度档选择 GUI（5 档） */
        改力度,
        /** 空位置左键点击 → 新增音符（默认 mf 力度，时值 1/16） */
        新增
    }

    /**
     * 编辑操作结果状态。
     */
    public enum 编辑结果 {
        /** 操作成功 */
        成功,
        /** 指定音符不存在（删除/移动/复制/改力度时找不到目标音符） */
        音符不存在,
        /** 时间位置或音高位置无效（越界或不在网格上） */
        位置无效,
        /** 音高超出乐器音域上下限 */
        音高越界,
        /** 编辑器未打开乐谱（乐谱为 null） */
        乐谱为空
    }

    private final 乐谱 编辑中乐谱;
    private final 乐谱 原始乐谱备份;

    /**
     * 构造编辑器。
     *
     * @param 编辑中乐谱 当前编辑中的乐谱（可被修改）
     * @param 原始乐谱备份 原始乐谱备份（不可变，用于恢复）
     */
    public 钢琴卷帘编辑器(乐谱 编辑中乐谱, 乐谱 原始乐谱备份) {
        this.编辑中乐谱 = 编辑中乐谱;
        this.原始乐谱备份 = 原始乐谱备份;
    }

    /**
     * 打开乐谱进入编辑器，备份原始乐谱。
     *
     * @param 原始 待编辑的乐谱；null 返回空编辑器
     * @return 新编辑器实例
     */
    public static 钢琴卷帘编辑器 打开(乐谱 原始) {
        if (原始 == null) {
            return new 钢琴卷帘编辑器(null, null);
        }
        乐谱 备份 = 复制乐谱(原始);
        return new 钢琴卷帘编辑器(复制乐谱(原始), 备份);
    }

    /**
     * 获取当前编辑中的乐谱（不可修改视图）。
     */
    public 乐谱 获取编辑中乐谱() {
        return 编辑中乐谱;
    }

    /**
     * 获取原始乐谱备份（用于恢复）。
     */
    public 乐谱 获取原始备份() {
        return 原始乐谱备份;
    }

    /**
     * 恢复到原始乐谱（撤销所有编辑）。
     *
     * @return 新编辑器实例，编辑中乐谱已恢复为原始备份的副本
     */
    public 钢琴卷帘编辑器 恢复原始() {
        if (原始乐谱备份 == null) {
            return this;
        }
        return new 钢琴卷帘编辑器(复制乐谱(原始乐谱备份), 原始乐谱备份);
    }

    /**
     * FP-20.3 删除指定索引的音符。
     *
     * @param 音符索引 待删除音符在音符列表中的索引（从 0 开始）
     * @return 新编辑器实例与结果状态的配对；失败时返回原实例
     */
    public 编辑操作配对 删除音符(int 音符索引) {
        if (编辑中乐谱 == null) {
            return new 编辑操作配对(this, 编辑结果.乐谱为空);
        }
        List<音符> 列表 = new ArrayList<>(编辑中乐谱.获取音符列表());
        if (音符索引 < 0 || 音符索引 >= 列表.size()) {
            return new 编辑操作配对(this, 编辑结果.音符不存在);
        }
        列表.remove(音符索引);
        乐谱 新乐谱 = 重建乐谱(列表);
        return new 编辑操作配对(new 钢琴卷帘编辑器(新乐谱, 原始乐谱备份), 编辑结果.成功);
    }

    /**
     * FP-20.3 移动指定索引的音符到新位置（时间顺序由调用方维护）。
     * 移动 = 删除原位置 + 在新位置插入（保留原音高与力度，仅改音高与时值）。
     *
     * @param 音符索引 待移动音符索引
     * @param 新音高   目标音高（0-24，需调用方校验乐器音域）
     * @param 新时值Tick 目标时值（必须 >= 最小时间单位tick）
     * @return 新编辑器实例与结果状态
     */
    public 编辑操作配对 移动音符(int 音符索引, int 新音高, int 新时值Tick) {
        if (编辑中乐谱 == null) {
            return new 编辑操作配对(this, 编辑结果.乐谱为空);
        }
        List<音符> 列表 = new ArrayList<>(编辑中乐谱.获取音符列表());
        if (音符索引 < 0 || 音符索引 >= 列表.size()) {
            return new 编辑操作配对(this, 编辑结果.音符不存在);
        }
        if (新时值Tick < 最小时间单位tick) {
            return new 编辑操作配对(this, 编辑结果.位置无效);
        }
        if (新音高 < 0 || 新音高 > 24) {
            return new 编辑操作配对(this, 编辑结果.音高越界);
        }
        音符 原音符 = 列表.get(音符索引);
        音符 新音符 = 音符.of(新音高, 新时值Tick, 原音符.获取力度());
        列表.set(音符索引, 新音符);
        乐谱 新乐谱 = 重建乐谱(列表);
        return new 编辑操作配对(new 钢琴卷帘编辑器(新乐谱, 原始乐谱备份), 编辑结果.成功);
    }

    /**
     * FP-20.3 复制指定索引的音符到新位置（保留原音符，新增副本）。
     *
     * @param 音符索引 待复制音符索引
     * @param 新音高   副本的音高
     * @param 新时值Tick 副本的时值
     * @return 新编辑器实例与结果状态
     */
    public 编辑操作配对 复制音符(int 音符索引, int 新音高, int 新时值Tick) {
        if (编辑中乐谱 == null) {
            return new 编辑操作配对(this, 编辑结果.乐谱为空);
        }
        List<音符> 列表 = new ArrayList<>(编辑中乐谱.获取音符列表());
        if (音符索引 < 0 || 音符索引 >= 列表.size()) {
            return new 编辑操作配对(this, 编辑结果.音符不存在);
        }
        if (新时值Tick < 最小时间单位tick) {
            return new 编辑操作配对(this, 编辑结果.位置无效);
        }
        if (新音高 < 0 || 新音高 > 24) {
            return new 编辑操作配对(this, 编辑结果.音高越界);
        }
        音符 原音符 = 列表.get(音符索引);
        音符 副本 = 音符.of(新音高, 新时值Tick, 原音符.获取力度());
        列表.add(副本);
        乐谱 新乐谱 = 重建乐谱(列表);
        return new 编辑操作配对(new 钢琴卷帘编辑器(新乐谱, 原始乐谱备份), 编辑结果.成功);
    }

    /**
     * FP-20.3 修改指定音符的力度档。
     *
     * @param 音符索引 待修改音符索引
     * @param 新力度   新力度值（0.0-1.0，由调用方从力度档转换）
     * @return 新编辑器实例与结果状态
     */
    public 编辑操作配对 改音符力度(int 音符索引, double 新力度) {
        if (编辑中乐谱 == null) {
            return new 编辑操作配对(this, 编辑结果.乐谱为空);
        }
        List<音符> 列表 = new ArrayList<>(编辑中乐谱.获取音符列表());
        if (音符索引 < 0 || 音符索引 >= 列表.size()) {
            return new 编辑操作配对(this, 编辑结果.音符不存在);
        }
        if (新力度 < 0.0 || 新力度 > 1.0) {
            return new 编辑操作配对(this, 编辑结果.位置无效);
        }
        音符 原音符 = 列表.get(音符索引);
        音符 新音符 = 音符.of(原音符.获取音高(), 原音符.获取时值Tick(), 新力度);
        列表.set(音符索引, 新音符);
        乐谱 新乐谱 = 重建乐谱(列表);
        return new 编辑操作配对(new 钢琴卷帘编辑器(新乐谱, 原始乐谱备份), 编辑结果.成功);
    }

    /**
     * FP-20.3 在指定位置新增音符（默认 mf 力度=0.75，时值 1/16）。
     *
     * @param 音高       新音符音高（0-24）
     * @param 时值Tick   新音符时值（必须 >= 最小时间单位tick）
     * @return 新编辑器实例与结果状态
     */
    public 编辑操作配对 新增音符(int 音高, int 时值Tick) {
        return 新增音符(音高, 时值Tick, 力度档.默认档().获取音量());
    }

    /**
     * FP-20.3 在指定位置新增音符（自定义力度）。
     *
     * @param 音高       新音符音高（0-24）
     * @param 时值Tick   新音符时值
     * @param 力度       新音符力度（0.0-1.0）
     * @return 新编辑器实例与结果状态
     */
    public 编辑操作配对 新增音符(int 音高, int 时值Tick, double 力度) {
        if (编辑中乐谱 == null) {
            return new 编辑操作配对(this, 编辑结果.乐谱为空);
        }
        if (时值Tick < 最小时间单位tick) {
            return new 编辑操作配对(this, 编辑结果.位置无效);
        }
        if (音高 < 0 || 音高 > 24) {
            return new 编辑操作配对(this, 编辑结果.音高越界);
        }
        if (力度 < 0.0 || 力度 > 1.0) {
            return new 编辑操作配对(this, 编辑结果.位置无效);
        }
        List<音符> 列表 = new ArrayList<>(编辑中乐谱.获取音符列表());
        列表.add(音符.of(音高, 时值Tick, 力度));
        乐谱 新乐谱 = 重建乐谱(列表);
        return new 编辑操作配对(new 钢琴卷帘编辑器(新乐谱, 原始乐谱备份), 编辑结果.成功);
    }

    /**
     * 获取编辑中乐谱的音符列表（不可修改视图）。
     * 编辑器未打开乐谱时返回空列表。
     */
    public List<音符> 获取音符列表() {
        if (编辑中乐谱 == null) {
            return Collections.emptyList();
        }
        return 编辑中乐谱.获取音符列表();
    }

    /**
     * 获取编辑中乐谱的音符数量。
     */
    public int 获取音符数量() {
        if (编辑中乐谱 == null) {
            return 0;
        }
        return 编辑中乐谱.获取音符数量();
    }

    /**
     * 编辑器是否已打开乐谱。
     */
    public boolean 是否已打开() {
        return 编辑中乐谱 != null;
    }

    /**
     * 复制乐谱（深拷贝音符列表）。
     */
    private static 乐谱 复制乐谱(乐谱 原始) {
        if (原始 == null) {
            return null;
        }
        List<音符> 副本 = new ArrayList<>(原始.获取音符列表());
        return new 乐谱(原始.获取名称(), 原始.获取作者标识(), 原始.获取作者名(),
                原始.获取创建时间戳(), 原始.获取速度BPM(), 副本);
    }

    /**
     * 用新音符列表重建乐谱（保留元数据）。
     */
    private 乐谱 重建乐谱(List<音符> 新音符列表) {
        return new 乐谱(编辑中乐谱.获取名称(), 编辑中乐谱.获取作者标识(), 编辑中乐谱.获取作者名(),
                编辑中乐谱.获取创建时间戳(), 编辑中乐谱.获取速度BPM(), 新音符列表);
    }

    /**
     * 编辑操作返回值：新编辑器实例 + 结果状态。
     */
    public static final class 编辑操作配对 {
        private final 钢琴卷帘编辑器 新编辑器;
        private final 编辑结果 结果;

        public 编辑操作配对(钢琴卷帘编辑器 新编辑器, 编辑结果 结果) {
            this.新编辑器 = 新编辑器;
            this.结果 = 结果;
        }

        public 钢琴卷帘编辑器 获取新编辑器() {
            return 新编辑器;
        }

        public 编辑结果 获取结果() {
            return 结果;
        }

        public boolean 是否成功() {
            return 结果 == 编辑结果.成功;
        }
    }
}
