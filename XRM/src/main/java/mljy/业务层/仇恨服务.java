package mljy.业务层;

import mljy.领域层.战斗.角色类型;

import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;

/**
 * 仇恨服务接口。
 * 管理怪物的仇恨列表，仇恨系数按职业区分（坦克3倍/治疗0.5倍/输出1倍）。
 * 40格距离检测，不需要视线也可以维持仇恨。
 * 仇恨自然消失条件：玩家已死亡、玩家距离超过40格、玩家不在线、怪物已死亡。
 * 注意：只要玩家不死且距离在40格内，仇恨不会随时间衰减。
 */
public interface 仇恨服务 {

    /**
     * 仇恨信息条目（结构化数据，供表现层格式化）。
     * 怪物名：怪物显示名；怪物标识：怪物UUID；玩家仇恨表：玩家名→仇恨值。
     */
    record 仇恨信息条目(String 怪物名, UUID 怪物标识, Map<String, Double> 玩家仇恨表) {
    }
    /**
     * 记录伤害产生的仇恨。
     * 仇恨值 = 伤害值 × 施法者角色类型的仇恨系数。
     */
    void 记录伤害仇恨(UUID 怪物标识, UUID 玩家标识, double 伤害值);

    /**
     * 记录伤害产生的仇恨（指定角色类型，避免重复查询）。
     */
    void 记录伤害仇恨(UUID 怪物标识, UUID 玩家标识, double 伤害值, 角色类型 施法者类型);

    /**
     * 记录治疗产生的仇恨。
     * 对所有正在攻击被治疗者的怪物，对治疗者产生仇恨。
     * 仇恨值 = 治疗值 × 治疗者角色类型的仇恨系数（治疗0.5倍）。
     */
    void 记录治疗仇恨(UUID 被治疗者标识, UUID 治疗者标识, double 治疗值);

    /**
     * 获取怪物的仇恨列表（玩家标识→仇恨值）。
     */
    Map<UUID, Double> 获取仇恨列表(UUID 怪物标识);

    /**
     * 获取怪物的仇恨最高目标。
     */
    Optional<UUID> 获取仇恨最高目标(UUID 怪物标识);

    /**
     * 获取怪物当前目标（仇恨最高者，自动切换目标）。
     */
    Optional<UUID> 获取当前目标(UUID 怪物标识);

    /**
     * 清除怪物的所有仇恨。
     */
    void 清除怪物仇恨(UUID 怪物标识);

    /**
     * 清除玩家在所有怪物中的仇恨。
     */
    void 清除玩家仇恨(UUID 玩家标识);

    /**
     * 清除范围内的怪物仇恨（管理员命令用）。
     */
    int 清除范围仇恨(UUID 中心玩家标识, double 范围);

    /**
     * 清除无效仇恨（玩家死亡/离线/距离超过40格/怪物死亡）。
     * 定时任务调用。
     */
    void 清除无效仇恨();

    /**
     * 获取附近怪物的仇恨信息（调试用）。
     * 返回结构化数据，由调用方负责格式化展示。
     */
    List<仇恨信息条目> 获取附近仇恨信息(UUID 中心玩家标识, double 范围);

    /**
     * 设置仇恨调试模式。
     */
    void 设置调试模式(boolean 开启);

    /**
     * 是否调试模式。
     */
    boolean 是否调试模式();

    /**
     * 获取仇恨系数（按角色类型）。
     */
    double 获取仇恨系数(角色类型 类型);
}
