package mljy.业务层;

import mljy.领域层.战斗.战斗状态;

import java.util.List;
import java.util.UUID;

/**
 * 战斗状态服务接口。
 * 管理玩家的战斗状态。
 * 进入战斗条件：造成伤害、受到伤害、治疗、释放技能。
 * 脱战判定：5秒无战斗行为自动脱战。
 * 脱战回血：基于生命恢复属性自动回复（生命恢复只有脱战情况下才会触发）。
 * 战斗中限制：禁止更换装备。
 */
public interface 战斗状态服务 {
    /**
     * 进入战斗（造成伤害/受到伤害/治疗/释放技能时调用）。
     * 使用独立UUID作为日志事件标识，不与挥剑事件合并。
     */
    void 进入战斗(UUID 玩家标识);

    /**
     * 进入战斗（带事件标识；用于挥剑事件合并）。
     * 事件标识非null时，进入战斗日志与挥剑事件共享事件标识（合并）；
     * 事件标识为null时，使用独立UUID（与旧接口行为一致）。
     */
    void 进入战斗(UUID 玩家标识, UUID 事件标识);

    /**
     * 获取战斗状态。
     */
    战斗状态 获取战斗状态(UUID 玩家标识);

    /**
     * 是否在战斗中。
     */
    boolean 是否战斗中(UUID 玩家标识);

    /**
     * 强制脱战（玩家死亡/退出等）。
     */
    void 强制脱战(UUID 玩家标识);

    /**
     * 刷新脱战状态（定时任务调用，检查5秒无战斗行为的玩家）。
     */
    void 刷新脱战();

    /**
     * 执行脱战回血（定时任务调用，每秒为脱战玩家恢复生命值）。
     */
    void 执行脱战回血();

    /**
     * 执行秘能衰减（定时任务调用，脱战后每5秒损失1层秘能）。
     */
    void 执行秘能衰减();

    /**
     * 设置调试模式。
     */
    void 设置调试模式(boolean 开启);

    /**
     * 是否调试模式。
     */
    boolean 是否调试模式();

    /**
     * 获取战斗中玩家列表（调试用）。
     */
    List<UUID> 获取战斗中玩家列表();
}
