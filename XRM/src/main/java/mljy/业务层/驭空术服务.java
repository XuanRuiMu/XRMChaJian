package mljy.业务层;

import mljy.领域层.驭空术.飞行状态;
import org.bukkit.entity.Player;

import java.util.UUID;

/**
 * 驭空术服务接口。
 * 管理玩家飞行状态、活力系统、4个技能（起飞/冲刺/爆发/俯冲）和BossBar显示。
 * 骑乘要求：玩家必须骑乘特定实体才能起飞。
 * 活力系统：飞行消耗活力，活力耗尽强制降落。
 */
public interface 驭空术服务 {

    /**
     * 起飞技能：从地面起飞，消耗活力，进入飞行状态。
     * 前置条件：玩家骑乘实体、活力充足、未在战斗中（若启用战斗限制）。
     */
    boolean 起飞(UUID 玩家标识);

    /**
     * 冲刺技能：飞行中向前冲刺，消耗活力，有冷却。
     */
    boolean 冲刺(UUID 玩家标识);

    /**
     * 爆发技能：飞行中向上爆发，消耗活力，有冷却。
     */
    boolean 爆发(UUID 玩家标识);

    /**
     * 俯冲技能：飞行中向下俯冲加速，消耗活力，有冷却。
     */
    boolean 俯冲(UUID 玩家标识);

    /**
     * 获取玩家当前飞行状态。
     */
    飞行状态 获取飞行状态(UUID 玩家标识);

    /**
     * 获取玩家当前活力值。
     */
    double 获取活力(UUID 玩家标识);

    /**
     * 获取玩家活力上限。
     */
    double 获取活力上限(UUID 玩家标识);

    /**
     * 获取冲刺技能剩余冷却（秒）。0表示就绪。
     */
    long 获取冲刺剩余冷却(UUID 玩家标识);

    /**
     * 获取爆发技能剩余冷却（秒）。0表示就绪。
     */
    long 获取爆发剩余冷却(UUID 玩家标识);

    /**
     * 获取俯冲技能剩余冷却（秒）。0表示就绪。
     */
    long 获取俯冲剩余冷却(UUID 玩家标识);

    /**
     * 每秒定时任务调用：处理活力消耗/恢复、活力耗尽强制降落。
     */
    void 每秒更新();

    /**
     * 每Tick定时任务调用：处理飞行物理、起飞过程、BossBar更新。
     */
    void 每Tick更新();

    /**
     * 强制结束玩家驭空状态（玩家退出/下坐骑/接触地面等）。
     */
    void 强制结束(UUID 玩家标识);

    /**
     * 玩家退出时清理资源。
     */
    void 玩家退出清理(UUID 玩家标识);

    /**
     * 检查玩家是否处于摔落保护期内。
     */
    boolean 是否摔落保护中(UUID 玩家标识);

    /**
     * 处理玩家切换飞行事件（防止原版飞行、进入准驭空/起飞）。
     * 返回true表示应取消原版飞行事件。
     */
    boolean 处理切换飞行(Player 玩家);

    /**
     * 玩家骑乘状态下双击空格进入准驭空状态。
     * 返回true表示成功进入准驭空状态。
     */
    boolean 尝试进入准驭空(Player 玩家);

    /**
     * 处理玩家移动事件（飞行物理）。
     * 返回true表示已处理该事件。
     */
    boolean 处理玩家移动(Player 玩家);
}
