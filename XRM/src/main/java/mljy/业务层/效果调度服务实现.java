package mljy.业务层;

import com.google.inject.Inject;
import com.google.inject.Injector;
import mljy.效果服务;
import mljy.基础设施层.事件日志上下文;
import mljy.基础设施层.调试日志器;
import mljy.领域层.效果.效果定义;
