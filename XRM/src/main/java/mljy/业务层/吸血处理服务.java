package mljy.业务层;

import mljy.领域层.玩家.玩家快照;

/**
 * 吸血处理服务接口。
 * 处理吸血逻辑：每拥有1点吸血，则每造成1点伤害或造成1点治疗时，都会按比例治疗自身。
 * 吸血触发的治疗为独立治疗，不触发任何加成/减益计算（包括吸血、全能、暴击、精通、治疗加成等），避免无限循环。
 * 通过战斗日志上下文管理器累加吸血量，确保吸血日志附加在伤害来源的日志中。
 */
public interface 吸血处理服务 {
    /**
     * 处理伤害吸血（造成伤害时调用）。
     * 施法者根据吸血属性按比例治疗自身，吸血量累加到战斗日志上下文。
     * 吸血治疗为独立治疗，不触发任何加成/减益计算，避免无限循环。
     */
    void 处理伤害吸血(玩家快照 施法者, double 伤害值);

    /**
     * 处理治疗吸血（造成治疗时调用）。
     * 施法者根据吸血属性按比例治疗自身，吸血量累加到战斗日志上下文。
     * 吸血治疗为独立治疗，不触发任何加成/减益计算，避免无限循环。
     */
    void 处理治疗吸血(玩家快照 施法者, double 治疗值);
}
