package mljy.业务层;

import mljy.领域层.组队.队伍;
import mljy.领域层.组队.组队操作结果;

import java.util.Optional;
import java.util.UUID;

/**
 * 组队服务接口。
 * 管理队伍创建/邀请/接受/拒绝/离开/踢出/解散/转让队长/就位检查。
 * 队伍ID = 队长UUID。
 * 邀请有效期可配置（默认30秒）。
 */
public interface 组队服务 {

    /**
     * 创建队伍。玩家成为队长。
     */
    组队操作结果 创建队伍(UUID 队长标识);

    /**
     * 邀请玩家加入队伍。仅队长可邀请。
     */
    组队操作结果 邀请玩家(UUID 队长标识, UUID 被邀请者标识);

    /**
     * 接受邀请加入队伍。
     */
    组队操作结果 接受邀请(UUID 玩家标识);

    /**
     * 拒绝邀请。
     */
    组队操作结果 拒绝邀请(UUID 玩家标识);

    /**
     * 离开队伍。队长离开自动转让队长或解散。
     */
    组队操作结果 离开队伍(UUID 玩家标识);

    /**
     * 踢出成员。仅队长可踢人。
     */
    组队操作结果 踢出成员(UUID 队长标识, UUID 成员标识);

    /**
     * 解散队伍。仅队长可解散。
     */
    组队操作结果 解散队伍(UUID 队长标识);

    /**
     * 转让队长。仅队长可转让。
     */
    组队操作结果 转让队长(UUID 队长标识, UUID 新队长标识);

    /**
     * 发起就位检查。仅队长可发起。
     */
    组队操作结果 发起就位检查(UUID 队长标识);

    /**
     * 确认就位。
     */
    组队操作结果 确认就位(UUID 玩家标识);

    /**
     * 获取玩家所在队伍。
     */
    Optional<队伍> 获取玩家队伍(UUID 玩家标识);

    /**
     * 获取队伍（按队长UUID）。
     */
    Optional<队伍> 获取队伍(UUID 队伍标识);

    /**
     * 玩家上线处理（恢复队伍状态）。
     */
    void 玩家上线(UUID 玩家标识);

    /**
     * 玩家下线处理（启动离线踢出计时）。
     */
    void 玩家下线(UUID 玩家标识);

    /**
     * 清理过期邀请。定时任务调用。
     */
    void 清理过期邀请();

    /**
     * 清理离线超时成员。定时任务调用。
     */
    void 清理离线超时成员();

    /**
     * 获取最大队伍人数。
     */
    int 获取最大队伍人数();
}
