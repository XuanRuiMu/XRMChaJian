package mljy.表现层.计分板;

import org.bukkit.entity.Player;

/**
 * 计分板服务接口。
 * 管理玩家计分板的创建、删除和更新。
 * 使用FastBoard实现，显示技能冷却和资源状态。
 */
public interface 计分板服务 {
    /**
     * 为玩家创建计分板。玩家加入时调用。
     */
    void 创建计分板(Player 玩家);

    /**
     * 删除玩家计分板。玩家退出时调用。
     */
    void 删除计分板(Player 玩家);

    /**
     * 更新玩家计分板内容。技能冷却或资源变化时调用。
     */
    void 更新计分板(Player 玩家);

    /**
     * 更新所有在线玩家的计分板。每秒定时调用。
     */
    void 更新所有计分板();

    /**
     * 只更新玩家计分板中特定技能的行。技能CD变化时调用，避免全量刷新。
     */
    void 更新技能行(Player 玩家, String 技能标识);

    /**
     * 只更新玩家计分板中的资源行。资源变化时调用，避免全量刷新。
     */
    void 更新资源行(Player 玩家);
}
