        @DisplayName("带--伤害系数=0.5的命令数组应使技能上下文读取到0.5")
        void 技能命令_带伤害系数覆盖_技能上下文应读取到覆盖值() {
            String[] 命令参数 = {"1_1", "目标玩家", "--伤害系数=0.5"};
            参数读取器 覆盖 = 参数读取器.从参数数组解析(命令参数, 2);

            技能定义 定义 = mock(技能定义.class);
            技能上下文 上下文 = new 技能上下文(
                    null, "1_1", 定义, null, System.currentTimeMillis(), 覆盖);

            参数读取器 上下文覆盖 = 上下文.获取参数覆盖();
            assertNotNull(上下文覆盖, "技能上下文应携带参数覆盖");
            assertTrue(上下文覆盖.是否有覆盖("伤害系数"),
                    "覆盖表应包含'伤害系数'键，实际: " + 上下文覆盖.获取覆盖表());
            assertEquals(0.5, 上下文覆盖.获取双精度("伤害系数", 1.0),
                    "技能实现读取'伤害系数'应得到0.5而非默认值1.0");
        }

