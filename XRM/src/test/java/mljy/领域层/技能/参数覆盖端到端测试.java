        @Test
        @DisplayName("GM命令裸key=value（无--前缀）应解析为覆盖，使弹道总长度等参数可被命令修改")
        void GM命令_裸弹道总长度_应解析为覆盖() {
            // FP-04 子问题C 复现：/guanli 技能 1_1 玄锐暮 弹道总长度=100.0
            // 真实命令参数数组为 ["技能","1_1","玄锐暮","弹道总长度=100.0"]（下标3起为覆盖）。
            // 旧实现要求 -- 前缀，裸 key=value 被静默丢弃，导致弹道长度始终为默认10.0。
            String[] 命令参数 = {"技能", "1_1", "玄锐暮", "弹道总长度=100.0"};
            参数读取器 覆盖 = 参数读取器.从参数数组解析(命令参数, 3);

            assertTrue(覆盖.是否有覆盖("弹道总长度"),
                    "裸 key=value 应被解析为覆盖，实际: " + 覆盖.获取覆盖表());
            assertEquals(100.0, 覆盖.获取双精度("弹道总长度", 10.0), 0.0001,
                    "弹道总长度覆盖应为100.0而非默认10.0");
        }

